/**
 * Local development stack WITHOUT Docker:
 *   - a development PostgreSQL database with the Supabase role/schema layout,
 *   - a real Supabase Auth (GoTrue) server pointed at it,
 *   - a tiny gateway that serves it under /auth/v1 like the Supabase API does.
 *
 * Usage: GOTRUE_BIN=/path/to/auth tsx scripts/dev/stack.ts up|down|reset|env
 * (With Docker you can use `supabase start` instead; see docs/DEVELOPMENT.md.)
 */
import { spawn, spawnSync } from "node:child_process";
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, openSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import pg from "pg";
import { migrate } from "../lib/migrate";

const root = resolve(import.meta.dirname, "../..");
const stateDir = resolve(root, ".local");
const envFile = resolve(root, ".env.local");
const DB = process.env.DEV_DB ?? "authenticity_dev";
const admin = process.env.DEV_PG_ADMIN_URL ?? "postgres://postgres:postgres@127.0.0.1:5432/postgres";
const GOTRUE_PORT = 9999;
const GATEWAY_PORT = 54321;

const b64 = (o: object) => Buffer.from(JSON.stringify(o)).toString("base64url");
function jwt(role: string, secret: string) {
  const head = b64({ alg: "HS256", typ: "JWT" });
  const body = b64({ role, iss: "local-dev", iat: Math.floor(Date.now() / 1000), exp: Math.floor(Date.now() / 1000) + 60 * 60 * 24 * 365 * 5 });
  return `${head}.${body}.${createHmac("sha256", secret).update(`${head}.${body}`).digest("base64url")}`;
}

function dbUrl(user: string, pw: string, db = DB) {
  const u = new URL(admin);
  u.username = user; u.password = pw; u.pathname = `/${db}`;
  return u.toString();
}

function writeEnv() {
  if (existsSync(envFile)) return JSON.parse(readFileSync(resolve(stateDir, "stack.json"), "utf8")) as { jwtSecret: string };
  const jwtSecret = randomBytes(32).toString("hex");
  const pepper = randomBytes(32).toString("hex");
  const lines = [
    "# Generated by scripts/dev/stack.ts for LOCAL DEVELOPMENT ONLY. Never commit.",
    `DATABASE_URL=${dbUrl("app_server", "app_server_dev_pw")}`,
    `VERIFIER_DATABASE_URL=${dbUrl("app_verifier", "app_verifier_dev_pw")}`,
    `DATABASE_ADMIN_URL=${dbUrl("postgres", new URL(admin).password)}`,
    `SUPABASE_URL=http://127.0.0.1:${GATEWAY_PORT}`,
    `SUPABASE_ANON_KEY=${jwt("anon", jwtSecret)}`,
    `SUPABASE_SERVICE_ROLE_KEY=${jwt("service_role", jwtSecret)}`,
    "PUBLIC_SITE_URL=http://localhost:3000",
    `NETWORK_HASH_PEPPER=${pepper}`,
    "ARTIFACT_STORAGE=local",
    "LOCAL_STORAGE_DIR=.local-storage",
    `CRON_SECRET=${randomBytes(24).toString("hex")}`,
    "REQUIRE_MFA_FOR_PRIVILEGED=false",
    "",
  ];
  mkdirSync(stateDir, { recursive: true });
  writeFileSync(envFile, lines.join("\n"), { mode: 0o600 });
  writeFileSync(resolve(stateDir, "stack.json"), JSON.stringify({ jwtSecret }), { mode: 0o600 });
  return { jwtSecret };
}

async function prepareDatabase(fresh: boolean) {
  const root0 = new pg.Client({ connectionString: admin });
  await root0.connect();
  try {
    if (fresh) {
      await root0.query("select pg_terminate_backend(pid) from pg_stat_activity where datname = $1 and pid <> pg_backend_pid()", [DB]);
      await root0.query(`drop database if exists ${DB}`);
    }
    const exists = (await root0.query("select 1 from pg_database where datname = $1", [DB])).rowCount;
    if (!exists) await root0.query(`create database ${DB}`);
  } finally {
    await root0.end();
  }

  const c = new pg.Client({ connectionString: dbUrl(new URL(admin).username, new URL(admin).password) });
  await c.connect();
  try {
    await c.query(`
      do $$ begin
        if not exists (select from pg_roles where rolname='supabase_auth_admin') then create role supabase_auth_admin login password 'auth_admin_dev_pw' createrole; end if;
        if not exists (select from pg_roles where rolname='anon') then create role anon nologin; end if;
        if not exists (select from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
        if not exists (select from pg_roles where rolname='service_role') then create role service_role nologin bypassrls; end if;
      end $$;
      alter role supabase_auth_admin login password 'auth_admin_dev_pw';
      create schema if not exists auth authorization supabase_auth_admin;
      grant all on schema public to supabase_auth_admin;
      grant usage on schema public, auth to anon, authenticated, service_role;
      alter role supabase_auth_admin set search_path = auth, public;`);
  } finally {
    await c.end();
  }
}

function gotrueEnv(secret: string): NodeJS.ProcessEnv {
  return {
    ...process.env,
    GOTRUE_DB_DRIVER: "postgres",
    DATABASE_URL: dbUrl("supabase_auth_admin", "auth_admin_dev_pw"),
    GOTRUE_DB_NAMESPACE: "auth",
    GOTRUE_JWT_SECRET: secret,
    GOTRUE_JWT_EXP: "3600",
    GOTRUE_JWT_AUD: "authenticated",
    GOTRUE_SITE_URL: "http://localhost:3000",
    GOTRUE_URI_ALLOW_LIST: "http://localhost:3000/**",
    API_EXTERNAL_URL: `http://127.0.0.1:${GATEWAY_PORT}`,
    GOTRUE_API_HOST: "127.0.0.1",
    PORT: String(GOTRUE_PORT),
    GOTRUE_DISABLE_SIGNUP: "true", // no public registration, ever
    GOTRUE_EXTERNAL_EMAIL_ENABLED: "true",
    GOTRUE_MAILER_AUTOCONFIRM: "true",
    GOTRUE_MFA_TOTP_ENROLL_ENABLED: "true",
    GOTRUE_MFA_TOTP_VERIFY_ENABLED: "true",
    GOTRUE_RATE_LIMIT_EMAIL_SENT: "1000",
    GOTRUE_SECURITY_REFRESH_TOKEN_ROTATION_ENABLED: "true",
    GOTRUE_LOG_LEVEL: "warn",
  };
}

function startDetached(name: string, cmd: string, args: string[], env: NodeJS.ProcessEnv) {
  mkdirSync(resolve(stateDir, "logs"), { recursive: true });
  const out = openSync(resolve(stateDir, "logs", `${name}.log`), "a");
  const child = spawn(cmd, args, { env, detached: true, stdio: ["ignore", out, out] });
  child.unref();
  writeFileSync(resolve(stateDir, `${name}.pid`), String(child.pid));
}

function stop(name: string) {
  const f = resolve(stateDir, `${name}.pid`);
  if (!existsSync(f)) return;
  try { process.kill(Number(readFileSync(f, "utf8")), "SIGTERM"); } catch { /* already gone */ }
}

async function waitFor(url: string, ms = 30_000) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try { if ((await fetch(url)).ok) return; } catch { /* retry */ }
    await new Promise((r) => setTimeout(r, 300));
  }
  throw new Error(`timed out waiting for ${url}`);
}

async function up(fresh = false) {
  const bin = process.env.GOTRUE_BIN;
  if (!bin || !existsSync(bin)) throw new Error("Set GOTRUE_BIN to a Supabase Auth (GoTrue) binary, or use `supabase start` instead (see docs/DEVELOPMENT.md).");
  if (fresh) { stop("gotrue"); stop("gateway"); spawnSync("rm", ["-f", envFile]); }
  const { jwtSecret } = writeEnv();
  await prepareDatabase(fresh);

  const env = gotrueEnv(jwtSecret);
  const mig = spawnSync(bin, ["migrate"], { env, encoding: "utf8" });
  if (mig.status !== 0) throw new Error(`auth migrate failed: ${mig.stderr || mig.stdout}`);

  const res = await migrate(dbUrl(new URL(admin).username, new URL(admin).password), resolve(root, "supabase/migrations"), (m) => console.log(m));
  console.log(`app migrations: ${res.applied.length} applied, ${res.skipped.length} up to date`);

  const c = new pg.Client({ connectionString: dbUrl(new URL(admin).username, new URL(admin).password) });
  await c.connect();
  await c.query("alter role app_server login password 'app_server_dev_pw'");
  await c.query("alter role app_verifier login password 'app_verifier_dev_pw'");
  await c.end();

  stop("gotrue"); stop("gateway");
  startDetached("gotrue", bin, ["serve"], env);
  startDetached("gateway", process.execPath, [resolve(import.meta.dirname, "gateway.mjs")], { ...process.env, GATEWAY_PORT: String(GATEWAY_PORT), GOTRUE_URL: `http://127.0.0.1:${GOTRUE_PORT}` });
  await waitFor(`http://127.0.0.1:${GOTRUE_PORT}/health`);
  await waitFor(`http://127.0.0.1:${GATEWAY_PORT}/auth/v1/health`);
  console.log(`stack ready: auth gateway http://127.0.0.1:${GATEWAY_PORT}, database ${DB}; env in .env.local`);
}

const cmd = process.argv[2];
(async () => {
  if (cmd === "up") await up(false);
  else if (cmd === "reset") await up(true);
  else if (cmd === "down") { stop("gotrue"); stop("gateway"); console.log("stopped"); }
  else { console.log("usage: stack.ts up|reset|down"); process.exit(1); }
})().catch((e) => { console.error(e.message); process.exit(1); });
